/* 𓁹𓁹: clean page addresses and security headers for static hosts.
 *
 * The Node server maps `/<slug>` to `t/<slug>.html` itself. Static hosts need
 * to be told, so this writes their config from the pages that actually exist:
 *
 *   `_redirects`   Cloudflare Pages: one `200` rule per page, which serves the
 *                  file without changing the address.
 *   `vercel.json`  Vercel: one rewrite per page, and the headers below.
 *
 * The Node server also sends security headers with every response. Static
 * hosts send them only if told, so both get the server's own table from
 * `dev-server.mjs`, with one difference: the server hashes each page's inline
 * scripts into its policy, which a static host cannot do, so there the policy
 * allows inline scripts instead. Scripts from any other origin stay refused.
 *
 *   `_headers`     Cloudflare Pages: the same headers, for every path.
 *
 * A static host also publishes every file it is given, where the Node server
 * publishes only `public-files.mjs` and `t/`. Two more files close that gap,
 * written from the same list so a new private file stays private everywhere:
 *
 *   `.vercelignore`  Vercel: leave private files out of the deployment.
 *   `_routes.json`   Cloudflare Pages: send requests for private paths to
 *                    `functions/[[path]].js`, which answers with the 404 page.
 *
 * Search engines are told about the same pages, in the registry's order:
 *
 *   `sitemap.xml`  every host: the index and each tool in `tools.js`, at the
 *                  address `site.js` gives as the site's own.
 *
 * Rewrites and headers only, deliberately. Neither can loop, and neither host
 * can be exercised from this repository, so the config is kept to what is safe
 * on both without testing. Old `/t/<slug>.html` addresses keep working on
 * static hosts; only the Node server also redirects them.
 *
 * Run after adding or removing a tool, a page in `t/` or a file at the top
 * level, or changing the security headers in `dev-server.mjs`:
 *
 *   node scripts/static-routes.mjs
 *
 * `npm run check` fails if the committed files are out of date.
 */

import { spawnSync } from 'node:child_process';
import { realpathSync } from 'node:fs';
import { readdir, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PUBLIC_ROOT_FILES } from '../public-files.mjs';
import { CSP, SECURITY_HEADER_VALUES, readRegistries } from '../dev-server.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Every page slug in `t/`, sorted so the output is stable. */
export async function pageSlugs() {
  return (await readdir(resolve(root, 't')))
    .filter(name => /^[a-z0-9-]+\.html$/.test(name))
    .map(name => name.slice(0, -'.html'.length))
    .sort();
}

/** The `sitemap.xml` for the index and these tools, on the site at `url`. */
export function sitemap(url, slugs) {
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated by scripts/static-routes.mjs. Do not edit by hand. -->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ...['', ...slugs].map(slug => `  <url><loc>${url}/${slug}</loc></url>`),
    '</urlset>',
    ''
  ].join('\n');
}

/** The Cloudflare Pages `_redirects` file for these slugs. */
export function pagesRedirects(slugs) {
  return [
    '# Generated by scripts/static-routes.mjs. Do not edit by hand.',
    '# Serves each tool at /<slug> without changing the address.',
    ...slugs.map(slug => `/${slug} /t/${slug} 200`),
    ''
  ].join('\n');
}

/* The server's security headers as a static host sends them. The policy ends
   in `script-src`, which is what the server appends hashes to. */
if (!/; script-src [^;]+$/.test(CSP)) throw new Error("dev-server.mjs: the CSP must end with script-src");
export const STATIC_HEADERS = Object.freeze({ ...SECURITY_HEADER_VALUES, 'Content-Security-Policy': CSP + " 'unsafe-inline'" });

/** The `vercel.json` for these slugs. */
export function vercelConfig(slugs) {
  return JSON.stringify({
    rewrites: slugs.map(slug => ({ source: '/' + slug, destination: '/t/' + slug + '.html' })),
    headers: [{ source: '/(.*)', headers: Object.entries(STATIC_HEADERS).map(([key, value]) => ({ key, value })) }]
  }, null, 2) + '\n';
}

/** The Cloudflare Pages `_headers` file. */
export function pagesHeaders() {
  return [
    '# Generated by scripts/static-routes.mjs. Do not edit by hand.',
    "# The Node server's security headers, for every path; see dev-server.mjs.",
    '/*',
    ...Object.entries(STATIC_HEADERS).map(([name, value]) => `  ${name}: ${value}`),
    ''
  ].join('\n');
}

/* Top-level entries every host publishes whole. */
const PUBLIC = new Set([...PUBLIC_ROOT_FILES.filter(path => !path.includes('/')), 't']);
/* Files published from inside a folder, such as the typeface in `fonts/`. The
   folder's other files stay private one by one. */
const PUBLIC_IN_FOLDERS = new Set(PUBLIC_ROOT_FILES.filter(path => path.includes('/')));
const PARTLY_PUBLIC = new Set([...PUBLIC_IN_FOLDERS].map(path => path.split('/')[0]));
/* Private entries Vercel must still be given: its own config, which it reads
   and never serves, and npm's `package.json`, which its project detection
   reads. */
const VERCEL_KEEPS = new Set(['vercel.json', '.vercelignore', 'package.json']);
/* Private entries Cloudflare Pages needs no rule for: its own config, which it
   reads and never serves. */
const PAGES_SKIPS = new Set(['_redirects', '_routes.json', '_headers']);

/**
 * Tracked entries a visitor must not be able to fetch, sorted: top-level
 * names, and single files in a folder that also publishes some. Read from git rather than the directory so local, ignored files never
 * change the output.
 * @returns {{name: string, dir: boolean}[]}
 */
export function privateEntries() {
  const listed = spawnSync('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8' });
  if (listed.status !== 0) throw new Error('static-routes needs a git checkout: ' + (listed.stderr || listed.error));
  const entries = new Map();
  for (const path of listed.stdout.split('\0').filter(Boolean)) {
    const [name, ...rest] = path.split('/');
    if (PUBLIC.has(name) || PUBLIC_IN_FOLDERS.has(path)) continue;
    const key = PARTLY_PUBLIC.has(name) ? path : name;
    entries.set(key, entries.get(key) || (key === name && rest.length > 0));
  }
  return [...entries].sort(([a], [b]) => (a < b ? -1 : 1)).map(([name, dir]) => ({ name, dir }));
}

/** The `.vercelignore` for these private entries. */
export function vercelIgnore(entries) {
  return [
    '# Generated by scripts/static-routes.mjs. Do not edit by hand.',
    '# Private files stay out of the deployment; see public-files.mjs.',
    ...entries.filter(entry => !VERCEL_KEEPS.has(entry.name)).map(entry => '/' + entry.name + (entry.dir ? '/' : '')),
    ''
  ].join('\n');
}

/** The Cloudflare Pages `_routes.json` for these private entries. */
export function pagesRoutes(entries) {
  const include = entries.filter(entry => !PAGES_SKIPS.has(entry.name)).map(entry => '/' + entry.name + (entry.dir ? '/*' : ''));
  /* Pages allows at most 100 rules. */
  if (include.length > 100) throw new Error('too many private top-level entries for _routes.json');
  return JSON.stringify({ version: 1, include, exclude: [] }, null, 2) + '\n';
}

/* Compared after resolving symlinks, because Node resolves them for the entry module. */
if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const slugs = await pageSlugs();
  await writeFile(resolve(root, '_redirects'), pagesRedirects(slugs));
  await writeFile(resolve(root, 'vercel.json'), vercelConfig(slugs));
  await writeFile(resolve(root, '_headers'), pagesHeaders());
  const entries = privateEntries();
  await writeFile(resolve(root, '.vercelignore'), vercelIgnore(entries));
  await writeFile(resolve(root, '_routes.json'), pagesRoutes(entries));
  const { site, tools } = await readRegistries();
  await writeFile(resolve(root, 'sitemap.xml'), sitemap(site.url, tools.map(tool => tool.slug)));
  console.log(`wrote _redirects, vercel.json and _headers for ${slugs.length} pages, .vercelignore and _routes.json for ${entries.length} private entries, and sitemap.xml for ${tools.length} tools`);
}
