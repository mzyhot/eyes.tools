/* 𓁹𓁹 — clean page addresses for static hosts.
 *
 * The Node server maps `/<slug>` to `t/<slug>.html` itself. Static hosts need
 * to be told, so this writes their config from the pages that actually exist:
 *
 *   `_redirects`   Cloudflare Pages: one `200` rule per page, which serves the
 *                  file without changing the address.
 *   `vercel.json`  Vercel: one rewrite per page.
 *
 * Rewrites only, deliberately. A rewrite cannot loop, and neither host can be
 * exercised from this repository, so the config is kept to the one behaviour
 * that is safe on both without testing. Old `/t/<slug>.html` addresses keep
 * working on static hosts; only the Node server also redirects them.
 *
 * Run after adding or removing a page in `t/`:
 *
 *   node scripts/static-routes.mjs
 *
 * `npm run check` fails if the committed files are out of date.
 */

import { readdir, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Every page slug in `t/`, sorted so the output is stable. */
export async function pageSlugs() {
  return (await readdir(resolve(root, 't')))
    .filter(name => /^[a-z0-9-]+\.html$/.test(name))
    .map(name => name.slice(0, -'.html'.length))
    .sort();
}

/** The Cloudflare Pages `_redirects` file for these slugs. */
export function pagesRedirects(slugs) {
  return [
    '# Generated by scripts/static-routes.mjs — do not edit by hand.',
    '# Serves each tool at /<slug> without changing the address.',
    ...slugs.map(slug => `/${slug} /t/${slug} 200`),
    ''
  ].join('\n');
}

/** The `vercel.json` for these slugs. */
export function vercelConfig(slugs) {
  return JSON.stringify({
    rewrites: slugs.map(slug => ({ source: '/' + slug, destination: '/t/' + slug + '.html' }))
  }, null, 2) + '\n';
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const slugs = await pageSlugs();
  await writeFile(resolve(root, '_redirects'), pagesRedirects(slugs));
  await writeFile(resolve(root, 'vercel.json'), vercelConfig(slugs));
  console.log(`wrote _redirects and vercel.json for ${slugs.length} pages`);
}
